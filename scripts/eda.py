"""Exploratory data analysis: figures + a markdown summary.

    python scripts/eda.py

Reads the raw CSV and the pipeline outputs, writes PNG figures to
docs/figures/ and the numbers to docs/EDA.md. Run after the pipeline.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from reviewrec.config import PROJECT_ROOT, get_settings  # noqa: E402
from reviewrec.data.load import load_raw  # noqa: E402

BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
INK, MUTED, GRID = "#0b0b0b", "#6f6d68", "#e1e0d9"


def style(ax, title, xlabel="", ylabel=""):
    ax.set_title(title, loc="left", fontsize=12, color=INK, pad=10)
    ax.set_xlabel(xlabel, color=MUTED)
    ax.set_ylabel(ylabel, color=MUTED)
    ax.tick_params(colors=MUTED)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color("#c3c2b7")
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def save(fig, path):
    fig.tight_layout()
    fig.savefig(path, dpi=130, facecolor="#fcfcfb")
    plt.close(fig)


def main() -> None:
    s = get_settings()
    fig_dir = PROJECT_ROOT / "docs" / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    raw = load_raw(s.path("paths.raw_csv"))
    products = pd.read_parquet(s.artifacts_dir / "products.parquet")
    mentions = pd.read_parquet(s.artifacts_dir / "mentions.parquet")
    report = json.loads((s.processed_dir / "data_quality_report.json").read_text())

    raw_words = raw["review_text"].fillna("").astype(str).str.split().str.len()
    lines = ["# Exploratory data analysis", "", "Generated by `scripts/eda.py` from the raw CSV and pipeline outputs.", ""]
    lines += [
        "## Raw file",
        "",
        f"- Rows: **{len(raw):,}**; distinct product titles: **{raw['product_title'].nunique():,}**; brands: **{raw['brand'].nunique():,}**",
        f"- Missing values: " + ", ".join(f"{c} {raw[c].isna().mean():.1%}" for c in ["product_title", "brand", "price", "rating", "review_text", "review_votes"]),
        f"- Review length (words): median **{raw_words.median():.0f}**, 90th percentile **{raw_words.quantile(0.9):.0f}**, max {raw_words.max():,}",
        f"- Star ratings: " + ", ".join(f"{k}★ {v:.1%}" for k, v in raw["rating"].value_counts(normalize=True).sort_index().items()),
        "",
        "## After cleaning (see data_quality_report.json)",
        "",
    ]
    lines += [f"- {k.replace('_', ' ')}: **{v:,}**" if isinstance(v, int) else f"- {k}: {v}" for k, v in report.items()]
    lines += [""]

    # 1. Ratings
    fig, ax = plt.subplots(figsize=(6, 3.4))
    counts = raw["rating"].value_counts().sort_index()
    ax.bar([f"{int(i)}★" for i in counts.index], counts.values, color=BLUE, width=0.6)
    style(ax, "Star-rating distribution (raw reviews)", ylabel="reviews")
    save(fig, fig_dir / "rating_distribution.png")

    # 2. Reviews per product (long tail)
    fig, ax = plt.subplots(figsize=(6, 3.4))
    per_title = raw.groupby("product_title").size()
    ax.hist(np.log10(per_title), bins=40, color=BLUE)
    ax.axvline(np.log10(s.get("data.min_reviews_per_product")), color=ORANGE, linewidth=2, label="inclusion threshold")
    ax.legend(frameon=False)
    style(ax, "Reviews per product title (log10)", xlabel="log10(reviews)", ylabel="titles")
    save(fig, fig_dir / "reviews_per_product.png")
    lines += [
        "## Long tail",
        "",
        f"- {(per_title < s.get('data.min_reviews_per_product')).mean():.1%} of titles have fewer than "
        f"{s.get('data.min_reviews_per_product')} reviews (cold start) and are excluded.",
        f"- The top 1% of titles hold {per_title.sort_values(ascending=False).head(max(1, len(per_title)//100)).sum() / per_title.sum():.1%} of reviews.",
        "",
    ]

    # 3. Review length
    fig, ax = plt.subplots(figsize=(6, 3.4))
    ax.hist(raw_words.clip(upper=200), bins=50, color=BLUE)
    style(ax, "Review length (words, clipped at 200)", xlabel="words", ylabel="reviews")
    save(fig, fig_dir / "review_length.png")

    # 4. Price
    fig, ax = plt.subplots(figsize=(6, 3.4))
    ax.hist(products["price"].dropna().clip(upper=1000), bins=40, color=BLUE)
    style(ax, "Product price (USD, clipped at 1000)", xlabel="price", ylabel="products")
    save(fig, fig_dir / "price_distribution.png")

    # 5. Brands
    fig, ax = plt.subplots(figsize=(6, 4))
    top = products.groupby("brand")["n_reviews"].sum().sort_values().tail(12)
    ax.barh(top.index, top.values, color=BLUE, height=0.6)
    style(ax, "Reviews by brand (top 12, included products)", xlabel="reviews")
    ax.grid(axis="x", color=GRID)
    ax.grid(axis="y", visible=False)
    save(fig, fig_dir / "top_brands.png")

    # 6. Aspects
    agg = mentions.groupby("aspect").agg(n=("mention_id", "count"), pos=("label", lambda x: (x == "positive").mean()),
                                         neg=("label", lambda x: (x == "negative").mean())).sort_values("n")
    fig, axes = plt.subplots(1, 2, figsize=(10, 4), sharey=True)
    axes[0].barh(agg.index, agg["n"], color=BLUE, height=0.6)
    style(axes[0], "Aspect mentions", xlabel="mentions")
    axes[1].barh(agg.index, agg["pos"] * 100, color=BLUE, height=0.6, label="positive")
    axes[1].barh(agg.index, -agg["neg"] * 100, color="#e34948", height=0.6, label="negative")
    axes[1].axvline(0, color="#c3c2b7")
    axes[1].legend(frameon=False, loc="lower right")
    style(axes[1], "Share of mentions (%)", xlabel="← negative | positive →")
    for ax in axes:
        ax.grid(axis="x", color=GRID)
        ax.grid(axis="y", visible=False)
    save(fig, fig_dir / "aspects.png")
    lines += ["## Aspect mentions", "", "| aspect | mentions | positive | negative |", "|---|---:|---:|---:|"]
    for a, r in agg.sort_values("n", ascending=False).iterrows():
        lines.append(f"| {a} | {int(r['n']):,} | {r['pos']:.1%} | {r['neg']:.1%} |")
    lines += ["", "## Figures", ""]
    for f in ["rating_distribution", "reviews_per_product", "review_length", "price_distribution", "top_brands", "aspects"]:
        lines.append(f"![{f}](figures/{f}.png)")
    (PROJECT_ROOT / "docs" / "EDA.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote docs/EDA.md and docs/figures/*.png")


if __name__ == "__main__":
    main()
